#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import readline from 'readline';
import pc from 'picocolors';
import crypto from 'crypto';
import { encodeLicensePayload, decodeLicensePayload } from './index';

const DEFAULT_ENDPOINT = 'https://license-tau-nine.vercel.app';
const CURRENT_VERSION = '^1.0.7';

type Framework = 'nextjs' | 'react' | 'vue' | 'unknown';

function detectFramework(cwd: string): Framework {
  const pkgPath = path.join(cwd, 'package.json');
  if (!fs.existsSync(pkgPath)) return 'unknown';
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    if (deps['next']) return 'nextjs';
    if (deps['vue']) return 'vue';
    if (deps['react']) return 'react';
  } catch { /* ignore */ }
  return 'unknown';
}

function ensurePackageDependency(cwd: string): boolean {
  const pkgPath = path.join(cwd, 'package.json');
  if (!fs.existsSync(pkgPath)) return false;
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
    if (!pkg.dependencies) pkg.dependencies = {};
    pkg.dependencies['@masdannn/license-guard'] = CURRENT_VERSION;
    fs.writeFileSync(pkgPath, JSON.stringify(pkg, null, 2), 'utf-8');
    return true;
  } catch {
    return false;
  }
}

function generateApiKey(): string {
  return 'LG-' + crypto.randomBytes(24).toString('hex');
}

function createPromptHelper() {
  const rl = readline.createInterface({
    input: process.stdin,
    output: process.stdout,
  });

  const ask = (query: string): Promise<string> => {
    return new Promise(resolve => {
      rl.question(query, answer => {
        resolve(answer.trim());
      });
    });
  };

  const close = () => {
    try {
      rl.close();
      if (process.stdin && typeof process.stdin.pause === 'function') {
        process.stdin.pause();
      }
      if (process.stdin && typeof process.stdin.unref === 'function') {
        process.stdin.unref();
      }
    } catch { /* ignore */ }
  };

  return { ask, close };
}

function setupFrameworkFiles(cwd: string, framework: Framework, encryptedKey: string): string[] {
  const lines: string[] = [];

  // Update/ensure package.json dependency
  if (ensurePackageDependency(cwd)) {
    lines.push(`  ${pc.green('✓')} Dependency: ${pc.bold('@masdannn/license-guard' + CURRENT_VERSION)}`);
  }

  const libContent = `'use client';

// ⚡ Auto-generated by @masdannn/license-guard — JANGAN DIHAPUS
import { initGuard } from '@masdannn/license-guard';

if (typeof window !== 'undefined') {
  initGuard({
    key: '${encryptedKey}',
  });
}
`;

  if (framework === 'nextjs') {
    const libDir = path.join(cwd, 'lib');
    if (!fs.existsSync(libDir)) fs.mkdirSync(libDir, { recursive: true });
    fs.writeFileSync(path.join(libDir, 'license-guard.ts'), libContent, 'utf-8');
    lines.push(`  ${pc.green('✓')} Dibuat: ${pc.bold('lib/license-guard.ts')} (encrypted key)`);

    const candidates = [
      { file: path.join(cwd, 'app', 'layout.tsx'), importLine: "import '@/lib/license-guard';" },
      { file: path.join(cwd, 'app', 'layout.jsx'), importLine: "import '@/lib/license-guard';" },
      { file: path.join(cwd, 'pages', '_app.tsx'), importLine: "import '@/lib/license-guard';" },
      { file: path.join(cwd, 'pages', '_app.jsx'), importLine: "import '@/lib/license-guard';" },
    ];
    let injected = false;
    for (const { file, importLine } of candidates) {
      if (fs.existsSync(file)) {
        const content = fs.readFileSync(file, 'utf-8');
        if (!content.includes('license-guard')) {
          fs.writeFileSync(file, importLine + '\n' + content, 'utf-8');
          lines.push(`  ${pc.green('✓')} Import ditambahkan ke: ${pc.bold(path.relative(cwd, file).replace(/\\/g, '/'))}`);
        } else {
          lines.push(`  ${pc.dim('·')} Import aktif di: ${pc.dim(path.relative(cwd, file).replace(/\\/g, '/'))}`);
        }
        injected = true;
        break;
      }
    }
    if (!injected) {
      lines.push(`  ${pc.yellow('!')} Tambahkan manual di root component: ${pc.cyan("import '@/lib/license-guard';")}`);
    }

  } else if (framework === 'react' || framework === 'vue') {
    const libDir = path.join(cwd, 'src', 'lib');
    if (!fs.existsSync(libDir)) fs.mkdirSync(libDir, { recursive: true });
    fs.writeFileSync(path.join(libDir, 'license-guard.ts'), libContent, 'utf-8');
    lines.push(`  ${pc.green('✓')} Dibuat: ${pc.bold('src/lib/license-guard.ts')} (encrypted key)`);

    const candidates = framework === 'react'
      ? [path.join(cwd, 'src', 'main.tsx'), path.join(cwd, 'src', 'main.jsx'), path.join(cwd, 'src', 'App.tsx')]
      : [path.join(cwd, 'src', 'main.ts'), path.join(cwd, 'src', 'main.js')];

    const importLine = "import './lib/license-guard';";
    let injected = false;
    for (const file of candidates) {
      if (fs.existsSync(file)) {
        const content = fs.readFileSync(file, 'utf-8');
        if (!content.includes('license-guard')) {
          fs.writeFileSync(file, importLine + '\n' + content, 'utf-8');
          lines.push(`  ${pc.green('✓')} Import ditambahkan ke: ${pc.bold(path.relative(cwd, file).replace(/\\/g, '/'))}`);
        } else {
          lines.push(`  ${pc.dim('·')} Import aktif di: ${pc.dim(path.relative(cwd, file).replace(/\\/g, '/'))}`);
        }
        injected = true;
        break;
      }
    }
    if (!injected) {
      lines.push(`  ${pc.yellow('!')} Tambahkan manual di ${pc.bold('src/main.ts')}: ${pc.cyan(importLine)}`);
    }

  } else {
    lines.push(`  ${pc.yellow('!')} Tambahkan manual di root aplikasi:`);
    lines.push(`     ${pc.cyan(`import { initGuard } from '@masdannn/license-guard';`)}`);
    lines.push(`     ${pc.cyan(`initGuard({ key: '${encryptedKey}' });`)}`);
  }

  return lines;
}

