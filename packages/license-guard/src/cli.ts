#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import pc from 'picocolors';

const DEFAULT_ENDPOINT = 'https://license-tau-nine.vercel.app';

// ─────────────────────────────────────────────────────────
// Framework Detection
// ─────────────────────────────────────────────────────────
type Framework = 'nextjs' | 'react' | 'vue' | 'unknown';

function detectFramework(cwd: string): Framework {
  const pkgPath = path.join(cwd, 'package.json');
  if (!fs.existsSync(pkgPath)) return 'unknown';
  try {
    const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
    const deps = { ...pkg.dependencies, ...pkg.devDependencies };
    if (deps['next']) return 'nextjs';
    if (deps['vue']) return 'vue';
    if (deps['react']) return 'react';
  } catch { /* ignore */ }
  return 'unknown';
}

// ─────────────────────────────────────────────────────────
// Auto-Setup: Create lib file + inject import
// ─────────────────────────────────────────────────────────
function setupFrameworkFiles(cwd: string, framework: Framework, apiKey: string, endpoint: string) {
  const lines: string[] = [];

  if (framework === 'nextjs') {
    // 1. Cari folder lib (app/lib atau lib)
    let libDir = path.join(cwd, 'lib');
    if (!fs.existsSync(libDir)) {
      const appLib = path.join(cwd, 'app', 'lib');
      libDir = fs.existsSync(appLib) ? appLib : libDir;
      if (!fs.existsSync(libDir)) fs.mkdirSync(libDir, { recursive: true });
    }

    const libFile = path.join(libDir, 'license-guard.ts');
    const libContent = `// ⚡ Auto-generated by @masdannn/license-guard
// Jangan hapus file ini — diperlukan untuk proteksi lisensi aktif
import { initGuard } from '@masdannn/license-guard';

if (typeof window !== 'undefined') {
  initGuard({
    apiKey: '${apiKey}',
    endpoint: '${endpoint}',
  });
}
`;
    fs.writeFileSync(libFile, libContent, 'utf-8');
    lines.push(`  ${pc.green('✅')} Dibuat: ${pc.bold('lib/license-guard.ts')}`);

    // 2. Coba inject import ke app/layout.tsx atau pages/_app.tsx
    const candidates = [
      path.join(cwd, 'app', 'layout.tsx'),
      path.join(cwd, 'app', 'layout.jsx'),
      path.join(cwd, 'pages', '_app.tsx'),
      path.join(cwd, 'pages', '_app.jsx'),
    ];

    let injected = false;
    for (const candidate of candidates) {
      if (fs.existsSync(candidate)) {
        const content = fs.readFileSync(candidate, 'utf-8');
        const importLine = "import '@/lib/license-guard';";
        if (!content.includes(importLine) && !content.includes('license-guard')) {
          const updated = importLine + '\n' + content;
          fs.writeFileSync(candidate, updated, 'utf-8');
          const rel = path.relative(cwd, candidate).replace(/\\/g, '/');
          lines.push(`  ${pc.green('✅')} Import ditambahkan ke: ${pc.bold(rel)}`);
          injected = true;
        } else {
          const rel = path.relative(cwd, candidate).replace(/\\/g, '/');
          lines.push(`  ${pc.yellow('⚠️')}  ${pc.bold(rel)} sudah mengandung import guard (dilewati)`);
          injected = true;
        }
        break;
      }
    }
    if (!injected) {
      lines.push(`  ${pc.yellow('⚠️')}  Root component tidak ditemukan. Tambahkan manual:`);
      lines.push(`     ${pc.cyan("import '@/lib/license-guard';")}`);
    }

  } else if (framework === 'react') {
    // React (CRA / Vite)
    let libDir = path.join(cwd, 'src', 'lib');
    if (!fs.existsSync(libDir)) fs.mkdirSync(libDir, { recursive: true });

    const libFile = path.join(libDir, 'license-guard.ts');
    const libContent = `// ⚡ Auto-generated by @masdannn/license-guard
import { initGuard } from '@masdannn/license-guard';

if (typeof window !== 'undefined') {
  initGuard({
    apiKey: '${apiKey}',
    endpoint: '${endpoint}',
  });
}
`;
    fs.writeFileSync(libFile, libContent, 'utf-8');
    lines.push(`  ${pc.green('✅')} Dibuat: ${pc.bold('src/lib/license-guard.ts')}`);

    // Inject ke src/main.tsx atau src/App.tsx
    const candidates = [
      path.join(cwd, 'src', 'main.tsx'),
      path.join(cwd, 'src', 'main.jsx'),
      path.join(cwd, 'src', 'App.tsx'),
      path.join(cwd, 'src', 'App.jsx'),
    ];

    let injected = false;
    for (const candidate of candidates) {
      if (fs.existsSync(candidate)) {
        const content = fs.readFileSync(candidate, 'utf-8');
        const importLine = "import './lib/license-guard';";
        if (!content.includes(importLine) && !content.includes('license-guard')) {
          fs.writeFileSync(candidate, importLine + '\n' + content, 'utf-8');
          const rel = path.relative(cwd, candidate).replace(/\\/g, '/');
          lines.push(`  ${pc.green('✅')} Import ditambahkan ke: ${pc.bold(rel)}`);
          injected = true;
        } else {
          const rel = path.relative(cwd, candidate).replace(/\\/g, '/');
          lines.push(`  ${pc.yellow('⚠️')}  ${pc.bold(rel)} sudah ada import guard (dilewati)`);
          injected = true;
        }
        break;
      }
    }
    if (!injected) {
      lines.push(`  ${pc.yellow('⚠️')}  Tidak bisa auto-inject. Tambahkan manual di ${pc.bold('src/main.tsx')}:`);
      lines.push(`     ${pc.cyan("import './lib/license-guard';")}`);
    }

  } else if (framework === 'vue') {
    // Vue
    let libDir = path.join(cwd, 'src', 'lib');
    if (!fs.existsSync(libDir)) fs.mkdirSync(libDir, { recursive: true });

    const libFile = path.join(libDir, 'license-guard.ts');
    const libContent = `// ⚡ Auto-generated by @masdannn/license-guard
import { initGuard } from '@masdannn/license-guard';

if (typeof window !== 'undefined') {
  initGuard({
    apiKey: '${apiKey}',
    endpoint: '${endpoint}',
  });
}
`;
    fs.writeFileSync(libFile, libContent, 'utf-8');
    lines.push(`  ${pc.green('✅')} Dibuat: ${pc.bold('src/lib/license-guard.ts')}`);

    const mainCandidates = [
      path.join(cwd, 'src', 'main.ts'),
      path.join(cwd, 'src', 'main.js'),
    ];

    let injected = false;
    for (const candidate of mainCandidates) {
      if (fs.existsSync(candidate)) {
        const content = fs.readFileSync(candidate, 'utf-8');
        const importLine = "import './lib/license-guard';";
        if (!content.includes(importLine) && !content.includes('license-guard')) {
          fs.writeFileSync(candidate, importLine + '\n' + content, 'utf-8');
          const rel = path.relative(cwd, candidate).replace(/\\/g, '/');
          lines.push(`  ${pc.green('✅')} Import ditambahkan ke: ${pc.bold(rel)}`);
          injected = true;
        } else {
          const rel = path.relative(cwd, candidate).replace(/\\/g, '/');
          lines.push(`  ${pc.yellow('⚠️')}  ${pc.bold(rel)} sudah ada import guard (dilewati)`);
          injected = true;
        }
        break;
      }
    }
    if (!injected) {
      lines.push(`  ${pc.yellow('⚠️')}  Tambahkan manual di ${pc.bold('src/main.ts')}:`);
      lines.push(`     ${pc.cyan("import './lib/license-guard';")}`);
    }

  } else {
    // Unknown — just show manual instructions
    lines.push(`  ${pc.yellow('⚠️')}  Framework tidak terdeteksi.`);
    lines.push(`  ${pc.bold('Tambahkan manual di root component Anda:')}`);
    lines.push(`     ${pc.cyan(`import { initGuard } from '@masdannn/license-guard';`)}`);
    lines.push(`     ${pc.cyan(`initGuard({ apiKey: '${apiKey}' });`)}`);
  }

  return lines;
}

// ─────────────────────────────────────────────────────────
// Main CLI
// ─────────────────────────────────────────────────────────
async function main() {
  const cwd = process.cwd();
  const endpoint = process.env.LICENSE_GUARD_SERVER || DEFAULT_ENDPOINT;
  const framework = detectFramework(cwd);

  const frameworkLabel: Record<Framework, string> = {
    nextjs: 'Next.js',
    react: 'React',
    vue: 'Vue',
    unknown: 'Unknown',
  };

  console.clear();
  console.log(pc.bold(pc.green('\n  🛡️  LICENSE GUARD — CLI PAIRING TOOL')));
  console.log(pc.dim('  ────────────────────────────────────────────────────────'));
  console.log(`  Framework  : ${pc.cyan(frameworkLabel[framework])}`);
  console.log(`  Directory  : ${pc.dim(cwd)}`);
  console.log(`  Server     : ${pc.dim(endpoint)}\n`);
  console.log(pc.yellow('  ⏳ Meminta Pairing Code dari Control Hub...'));

  try {
    const res = await fetch(`${endpoint}/api/pairing/request`, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
    });

    const data = await res.json();

    if (!res.ok || !data.success) {
      console.error(pc.red(`\n  ❌ Gagal: ${data.error || 'Server error'}`));
      process.exit(1);
    }

    const pairingCode: string = data.code;

    console.clear();
    console.log(pc.bold(pc.green('\n  🛡️  LICENSE GUARD — CLI PAIRING TOOL')));
    console.log(pc.dim('  ────────────────────────────────────────────────────────\n'));

    console.log(pc.bold('  PAIRING CODE:'));
    console.log(pc.bgBlack(pc.bold(pc.yellow(`\n    ${pairingCode}\n`))));

    console.log(pc.bold('  Langkah Selanjutnya:'));
    console.log(`  ${pc.dim('1.')} Buka Dashboard: ${pc.cyan(`${endpoint}/projects/new`)}`);
    console.log(`  ${pc.dim('2.')} Masukkan nama project, domain, dan kode: ${pc.yellow(pc.bold(pairingCode))}`);
    console.log(`  ${pc.dim('3.')} Klik ${pc.bold(pc.green('[PAIR & CONNECT]'))}\n`);
    console.log(pc.dim('  ────────────────────────────────────────────────────────'));
    console.log(pc.yellow('  ⏳ Menunggu konfirmasi... (Ctrl+C untuk batal)\n'));

    // Polling
    const pollInterval = 2500;
    const maxAttempts = 240;
    let attempts = 0;

    const timer = setInterval(async () => {
      attempts++;
      if (attempts > maxAttempts) {
        clearInterval(timer);
        console.log(pc.red('\n  ⌛ Sesi pairing kedaluwarsa. Jalankan ulang CLI.'));
        process.exit(1);
      }

      try {
        const checkRes = await fetch(`${endpoint}/api/pairing/status?code=${pairingCode}`);
        const checkData = await checkRes.json();

        if (checkData.status === 'CLAIMED') {
          clearInterval(timer);
          const apiKey: string = checkData.apiKey;

          console.clear();
          console.log(pc.bold(pc.green('\n  ✅ PAIRING BERHASIL!')));
          console.log(pc.dim('  ────────────────────────────────────────────────────────\n'));
          console.log(`  Project ID : ${pc.bold(checkData.projectId)}`);
          console.log(`  Domain     : ${pc.bold(checkData.domain)}`);
          console.log(`  API Key    : ${pc.cyan(apiKey)}\n`);

          // Simpan .licenseguard.json
          const configPath = path.join(cwd, '.licenseguard.json');
          const configData = {
            projectId: checkData.projectId,
            apiKey,
            domain: checkData.domain,
            endpoint,
            framework: frameworkLabel[framework],
            pairedAt: new Date().toISOString(),
          };
          fs.writeFileSync(configPath, JSON.stringify(configData, null, 2), 'utf-8');
          console.log(`  ${pc.green('✅')} Config: ${pc.bold('.licenseguard.json')}`);

          // Auto-setup framework files
          console.log(pc.bold('\n  ⚡ Setup Otomatis:'));
          const setupLines = setupFrameworkFiles(cwd, framework, apiKey, endpoint);
          setupLines.forEach(l => console.log(l));

          console.log(pc.dim('\n  ────────────────────────────────────────────────────────'));
          console.log(pc.bold(pc.green('  🛡️  Website Anda kini terlindungi oleh License Guard!\n')));
          process.exit(0);

        } else if (checkData.status === 'EXPIRED') {
          clearInterval(timer);
          console.log(pc.red('\n  ❌ Kode pairing kedaluwarsa.'));
          process.exit(1);
        }
      } catch {
        // abaikan error transient
      }
    }, pollInterval);

  } catch (err) {
    console.error(pc.red(`\n  ❌ Gagal terhubung: ${err instanceof Error ? err.message : err}`));
    process.exit(1);
  }
}

main();
